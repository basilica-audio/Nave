#!/usr/bin/env python3
"""Analytical cabinet impulse-response synthesiser.

WHY THIS EXISTS
---------------
Bundling a cabinet impulse response means redistributing a recording inside
every copy of an AGPLv3 binary. Third-party IR packs make that a licensing
question that is frequently unanswerable: a capture carries rights from the
cabinet, from the microphone, and from the person who pressed record, and
mirrors routinely misstate all three.

This script sidesteps the question entirely. Every IR it emits is *computed*
from a documented analytical model - a cascade of standard analog-prototype
filter sections plus sparse reflection taps - and therefore contains no
third-party recording at all. The generator is the provenance: run it, get
byte-identical output, compare the SHA-256. That is a stronger licence
argument than any pack's README.

WHAT THESE ARE, AND WHAT THEY ARE NOT
-------------------------------------
These are MODELS. They are not captures of any particular cabinet, speaker or
microphone, they are not measurements, and they must never be labelled as if
they were. Every display name carries a "Modelled" prefix for exactly that
reason. The models are voiced from the well-documented behaviour of moving-coil
loudspeakers in boxes - driver/box high-pass alignment, cone-breakup modes,
voice-coil-inductance roll-off, baffle and floor reflections, microphone
proximity and off-axis behaviour - not from anyone's recording.

MODEL STRUCTURE
---------------
Each model is one or more parallel *paths* (a woofer path, optionally a horn
path), each path being a gain, an integer sample delay, and an ordered chain of
biquad sections. The summed direct field is then run through a sparse FIR of
reflection taps whose delays are derived from a physical path-length difference
in centimetres at 343 m/s, and optionally summed with a decaying diffuse tail
generated by an explicitly-seeded LCG.

Filter sections use the standard bilinear-transform designs (RBJ audio EQ
cookbook), evaluated in float64. There is no randomness anywhere except the
diffuse tail, whose generator and seed are part of the model definition, so the
output is bit-identical on any machine with an IEEE-754 double.

DEPENDENCIES
------------
The Python standard library, and nothing else. No numpy, no scipy, no network
access. This is deliberate: a generator that needs a pinned scientific stack to
reproduce its output is a weaker reproducibility claim than one that does not.

USAGE
-----
    python3 cabsynth.py --out-dir ../../resources/irs --models bass
    python3 cabsynth.py --list
    python3 cabsynth.py --manifest manifest.json --out-dir out
"""

