def select_models(selector):
    if selector in (None, "all"):
        return list(MODELS.values())
    wanted = [token.strip() for token in selector.split(",") if token.strip()]
    chosen = []
    for token in wanted:
        if token in MODELS:
            chosen.append(MODELS[token])
            continue
        family = [model for model in MODELS.values() if model["family"] == token]
        if not family:
            raise SystemExit("unknown model or family: %s" % token)
        chosen.extend(family)
    # De-duplicate while keeping the declaration order stable.
    seen = set()
    ordered = []
    for model in MODELS.values():
        if model["id"] in {m["id"] for m in chosen} and model["id"] not in seen:
            seen.add(model["id"])
            ordered.append(model)
    return ordered


def describe_stage(stage):
    parts = [stage["type"], "%.1f Hz" % stage["freq"]]
    if "q" in stage:
        parts.append("Q %.2f" % stage["q"])
    if "gain_db" in stage:
        parts.append("%+.1f dB" % stage["gain_db"])
    return " ".join(parts)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out-dir", help="directory to write the .wav files into")
    parser.add_argument("--models", default="all",
                        help="comma-separated model ids or families (bass, guitar), or 'all'")
    parser.add_argument("--manifest", help="write a JSON manifest of what was generated")
    parser.add_argument("--list", action="store_true", help="list the models and exit")
    args = parser.parse_args(argv)

    if args.list:
        for model in MODELS.values():
            print("%-22s %-30s %s" % (model["id"], model["display_name"], model["description"]))
        return 0

    if not args.out_dir:
        parser.error("--out-dir is required unless --list is given")

    os.makedirs(args.out_dir, exist_ok=True)

    manifest = {
        "generator": os.path.basename(__file__),
        "generator_sha256": hashlib.sha256(open(__file__, "rb").read()).hexdigest(),
        "speed_of_sound_m_per_s": SPEED_OF_SOUND_M_PER_S,
        "normalisation": "unity peak magnitude response (max |H(f)| = 1.0)",
        "irs": [],
    }

    for model in select_models(args.models):
        impulse = render_model(model)
        normalised, scale, raw_peak = normalise_unity_peak_response(impulse)

        out_path = os.path.join(args.out_dir, model["file_name"])
        clipped, peak_sample = write_wav24(out_path, normalised, model["sample_rate"])
        if clipped:
            raise SystemExit("%s: %d samples clipped on quantisation" % (out_path, clipped))

        digest = hashlib.sha256(open(out_path, "rb").read()).hexdigest()

        stage_lines = []
        for path in model["paths"]:
            for stage in path["stages"]:
                stage_lines.append("%s: %s" % (path["label"], describe_stage(stage)))

        manifest["irs"].append({
            "id": model["id"],
            "display_name": model["display_name"],
            "file": model["file_name"],
            "family": model["family"],
            "description": model["description"],
            "sample_rate": model["sample_rate"],
            "length_samples": model["length"],
            "length_ms": round(1000.0 * model["length"] / model["sample_rate"], 2),
            "channels": 1,
            "bit_depth": 24,
            "normalisation_scale": scale,
            "pre_normalisation_peak_response": raw_peak,
            "peak_sample": round(peak_sample, 6),
            "sections": stage_lines,
            "reflections": [
                {"path_cm": r["path_cm"], "gain": r["gain"],
                 "delay_samples": delay_samples_for_path_cm(r["path_cm"], model["sample_rate"])}
                for r in model.get("reflections", [])
            ],
            "tail": model.get("tail"),
            "sha256": digest,
        })

        print("%-34s %5d samples  %6.2f ms  peak %.4f  sha256 %s"
              % (model["file_name"], model["length"], manifest["irs"][-1]["length_ms"],
                 peak_sample, digest[:16]))

    if args.manifest:
        with open(args.manifest, "w") as handle:
            json.dump(manifest, handle, indent=2, sort_keys=True)
            handle.write("\n")
        print("manifest: %s" % args.manifest)

    return 0


if __name__ == "__main__":
    sys.exit(main())
