# Speed of sound in air at 20 degrees C, in metres per second. Used to convert
# a reflection's excess path length (in centimetres) into a delay in samples.
SPEED_OF_SOUND_M_PER_S = 343.0


# ---------------------------------------------------------------------------
# Biquad section design (bilinear transform, RBJ audio EQ cookbook forms).
# Coefficients are returned normalised to a0 = 1 as (b0, b1, b2, a1, a2).
# ---------------------------------------------------------------------------

def _rbj_common(freq_hz, sample_rate, q):
    w0 = 2.0 * math.pi * freq_hz / sample_rate
    cos_w0 = math.cos(w0)
    sin_w0 = math.sin(w0)
    alpha = sin_w0 / (2.0 * q)
    return w0, cos_w0, sin_w0, alpha


def biquad_lowpass(freq_hz, sample_rate, q):
    _, cos_w0, _, alpha = _rbj_common(freq_hz, sample_rate, q)
    b0 = (1.0 - cos_w0) / 2.0
    b1 = 1.0 - cos_w0
    b2 = (1.0 - cos_w0) / 2.0
    a0 = 1.0 + alpha
    a1 = -2.0 * cos_w0
    a2 = 1.0 - alpha
    return (b0 / a0, b1 / a0, b2 / a0, a1 / a0, a2 / a0)


def biquad_highpass(freq_hz, sample_rate, q):
    _, cos_w0, _, alpha = _rbj_common(freq_hz, sample_rate, q)
    b0 = (1.0 + cos_w0) / 2.0
    b1 = -(1.0 + cos_w0)
    b2 = (1.0 + cos_w0) / 2.0
    a0 = 1.0 + alpha
    a1 = -2.0 * cos_w0
    a2 = 1.0 - alpha
    return (b0 / a0, b1 / a0, b2 / a0, a1 / a0, a2 / a0)


def biquad_highpass1(freq_hz, sample_rate, q=None):
    """First-order high-pass, expressed as a biquad with b2 = a2 = 0.

    Used for the 6 dB/octave dipole roll-off of an open-back cabinet, which is
    a first-order slope and would be misrepresented by a second-order section.
    """
    k = math.tan(math.pi * freq_hz / sample_rate)
    norm = 1.0 / (1.0 + k)
    return (norm, -norm, 0.0, (k - 1.0) * norm, 0.0)


def biquad_peaking(freq_hz, sample_rate, q, gain_db):
    amp = 10.0 ** (gain_db / 40.0)
    _, cos_w0, _, alpha = _rbj_common(freq_hz, sample_rate, q)
    b0 = 1.0 + alpha * amp
    b1 = -2.0 * cos_w0
    b2 = 1.0 - alpha * amp
    a0 = 1.0 + alpha / amp
    a1 = -2.0 * cos_w0
    a2 = 1.0 - alpha / amp
    return (b0 / a0, b1 / a0, b2 / a0, a1 / a0, a2 / a0)


def biquad_lowshelf(freq_hz, sample_rate, q, gain_db):
    amp = 10.0 ** (gain_db / 40.0)
    w0, cos_w0, sin_w0, _ = _rbj_common(freq_hz, sample_rate, q)
    alpha = sin_w0 / 2.0 * math.sqrt((amp + 1.0 / amp) * (1.0 / q - 1.0) + 2.0)
    two_sqrt_a_alpha = 2.0 * math.sqrt(amp) * alpha
    b0 = amp * ((amp + 1.0) - (amp - 1.0) * cos_w0 + two_sqrt_a_alpha)
    b1 = 2.0 * amp * ((amp - 1.0) - (amp + 1.0) * cos_w0)
    b2 = amp * ((amp + 1.0) - (amp - 1.0) * cos_w0 - two_sqrt_a_alpha)
    a0 = (amp + 1.0) + (amp - 1.0) * cos_w0 + two_sqrt_a_alpha
    a1 = -2.0 * ((amp - 1.0) + (amp + 1.0) * cos_w0)
    a2 = (amp + 1.0) + (amp - 1.0) * cos_w0 - two_sqrt_a_alpha
    return (b0 / a0, b1 / a0, b2 / a0, a1 / a0, a2 / a0)


def biquad_highshelf(freq_hz, sample_rate, q, gain_db):
    amp = 10.0 ** (gain_db / 40.0)
    w0, cos_w0, sin_w0, _ = _rbj_common(freq_hz, sample_rate, q)
    alpha = sin_w0 / 2.0 * math.sqrt((amp + 1.0 / amp) * (1.0 / q - 1.0) + 2.0)
    two_sqrt_a_alpha = 2.0 * math.sqrt(amp) * alpha
    b0 = amp * ((amp + 1.0) + (amp - 1.0) * cos_w0 + two_sqrt_a_alpha)
    b1 = -2.0 * amp * ((amp - 1.0) + (amp + 1.0) * cos_w0)
    b2 = amp * ((amp + 1.0) + (amp - 1.0) * cos_w0 - two_sqrt_a_alpha)
    a0 = (amp + 1.0) - (amp - 1.0) * cos_w0 + two_sqrt_a_alpha
    a1 = 2.0 * ((amp - 1.0) - (amp + 1.0) * cos_w0)
    a2 = (amp + 1.0) - (amp - 1.0) * cos_w0 - two_sqrt_a_alpha
    return (b0 / a0, b1 / a0, b2 / a0, a1 / a0, a2 / a0)


_SECTION_DESIGNERS = {
    "lowpass": lambda s, sr: biquad_lowpass(s["freq"], sr, s["q"]),
    "highpass": lambda s, sr: biquad_highpass(s["freq"], sr, s["q"]),
    "highpass1": lambda s, sr: biquad_highpass1(s["freq"], sr),
    "peak": lambda s, sr: biquad_peaking(s["freq"], sr, s["q"], s["gain_db"]),
    "lowshelf": lambda s, sr: biquad_lowshelf(s["freq"], sr, s["q"], s["gain_db"]),
    "highshelf": lambda s, sr: biquad_highshelf(s["freq"], sr, s["q"], s["gain_db"]),
}


def apply_biquad(signal, coeffs):
    """Direct Form I, float64, zero initial state."""
    b0, b1, b2, a1, a2 = coeffs
    x1 = x2 = y1 = y2 = 0.0
    out = [0.0] * len(signal)
    for n, x0 in enumerate(signal):
        y0 = b0 * x0 + b1 * x1 + b2 * x2 - a1 * y1 - a2 * y2
        out[n] = y0
        x2, x1 = x1, x0
        y2, y1 = y1, y0
    return out


def apply_chain(signal, stages, sample_rate):
    out = signal
    for stage in stages:
        designer = _SECTION_DESIGNERS[stage["type"]]
        out = apply_biquad(out, designer(stage, sample_rate))
    return out


# ---------------------------------------------------------------------------
# Deterministic noise for the diffuse tail of a room model.
#
# An explicit 64-bit LCG (the constants are Knuth's MMIX ones) rather than
# random.Random, so the sample stream is defined by this file alone and cannot
# drift with a Python release.
# ---------------------------------------------------------------------------

class Lcg:
    MULTIPLIER = 6364136223846793005
    INCREMENT = 1442695040888963407
    MODULUS = 1 << 64

    def __init__(self, seed):
        self.state = seed % self.MODULUS

    def next_bipolar(self):
        self.state = (self.state * self.MULTIPLIER + self.INCREMENT) % self.MODULUS
        # Take the top 32 bits: the low bits of an LCG have short periods.
        top = self.state >> 32
        return (top / 2147483648.0) - 1.0


# ---------------------------------------------------------------------------
# Radix-2 FFT (iterative, in-place Cooley-Tukey) - used only for the
# normalisation measurement, never in the IR itself.
# ---------------------------------------------------------------------------

def fft(values):
    n = len(values)
    if n & (n - 1) != 0:
        raise ValueError("FFT length must be a power of two")

    data = list(values)
    j = 0
    for i in range(1, n):
        bit = n >> 1
        while j & bit:
            j ^= bit
            bit >>= 1
        j |= bit
        if i < j:
            data[i], data[j] = data[j], data[i]

    length = 2
    while length <= n:
        angle = -2.0 * math.pi / length
        step = complex(math.cos(angle), math.sin(angle))
        for start in range(0, n, length):
            w = complex(1.0, 0.0)
            half = length >> 1
            for k in range(start, start + half):
                u = data[k]
                v = data[k + half] * w
                data[k] = u + v
                data[k + half] = u - v
                w *= step
        length <<= 1
    return data


def magnitude_response(impulse, fft_size):
    padded = [complex(x, 0.0) for x in impulse] + [0j] * (fft_size - len(impulse))
    spectrum = fft(padded)
    return [abs(spectrum[k]) for k in range(fft_size // 2 + 1)]


# ---------------------------------------------------------------------------
# Model rendering
# ---------------------------------------------------------------------------

def delay_samples_for_path_cm(path_cm, sample_rate):
    seconds = (path_cm / 100.0) / SPEED_OF_SOUND_M_PER_S
    return int(round(seconds * sample_rate))


def render_model(model):
    sample_rate = model["sample_rate"]
    length = model["length"]

    # Render each parallel path from its own unit impulse, then sum. Rendering
    # at 4x the final length and truncating afterwards keeps the tail of a
    # resonant section from being cut before it has decayed into the noise.
    work_length = length * 4
    summed = [0.0] * work_length

    for path in model["paths"]:
        impulse = [0.0] * work_length
        impulse[0] = 1.0
        rendered = apply_chain(impulse, path["stages"], sample_rate)
        gain = path.get("gain", 1.0)
        delay = path.get("delay_samples", 0)
        for n in range(work_length - delay):
            summed[n + delay] += gain * rendered[n]

    # Sparse reflection FIR. Each tap is a copy of the whole direct field,
    # delayed by its excess path length and scaled; a negative gain models a
    # polarity-inverting boundary interaction.
    reflected = list(summed)
    for reflection in model.get("reflections", []):
        delay = delay_samples_for_path_cm(reflection["path_cm"], sample_rate)
        gain = reflection["gain"]
        # A reflection has travelled further through air and off a surface, so
        # it arrives duller than the direct sound.
        damped = apply_chain(summed, reflection.get("stages", []), sample_rate)
        for n in range(work_length - delay):
            reflected[n + delay] += gain * damped[n]

    tail_spec = model.get("tail")
    if tail_spec is not None:
        reflected = _add_diffuse_tail(reflected, tail_spec, model, work_length)

    truncated = reflected[:length]

    # Raised-cosine fade so truncation cannot leave a step discontinuity (which
    # would read as broadband splatter in the frequency response).
    fade = model.get("fade_samples", max(16, length // 4))
    fade = min(fade, length)
    for i in range(fade):
        position = i / float(fade)
        truncated[length - fade + i] *= 0.5 * (1.0 + math.cos(math.pi * position))

    return truncated


def _add_diffuse_tail(direct, tail_spec, model, work_length):
    sample_rate = model["sample_rate"]
    rng = Lcg(tail_spec["seed"])
    decay_tau = tail_spec["decay_seconds"] * sample_rate
    predelay = delay_samples_for_path_cm(tail_spec["predelay_cm"], sample_rate)

    noise = [0.0] * work_length
    for n in range(predelay, work_length):
        noise[n] = rng.next_bipolar() * math.exp(-(n - predelay) / decay_tau)

    shaped = apply_chain(noise, tail_spec.get("stages", []), sample_rate)

    # Level the tail against the direct field by energy, so the documented
    # "tail is N dB below direct" number means what it says.
    direct_energy = math.sqrt(sum(v * v for v in direct)) or 1.0
    tail_energy = math.sqrt(sum(v * v for v in shaped)) or 1.0
    scale = (direct_energy / tail_energy) * (10.0 ** (tail_spec["level_db"] / 20.0))

    return [direct[n] + scale * shaped[n] for n in range(work_length)]


def normalise_unity_peak_response(impulse, fft_size=65536):
    """Scale so that max |H(f)| == 1.0 (0 dBFS).

    Chosen over peak-sample or energy normalisation because it is the criterion
    that actually bounds the convolution: with the maximum of the magnitude
    response at unity, no sine at any frequency can leave the convolver louder
    than it entered, so a full-scale input cannot be driven into clipping by
    the IR alone. It is also trivially verifiable after the fact, which matters
    more here than matching anyone's loudness convention - both host plugins
    apply their own IR gain staging downstream.
    """
    response = magnitude_response(impulse, fft_size)
    peak = max(response)
    if peak <= 0.0:
        raise ValueError("degenerate impulse response: zero magnitude everywhere")
    scale = 1.0 / peak
    return [v * scale for v in impulse], scale, peak


# ---------------------------------------------------------------------------
# 24-bit PCM WAV writing (little-endian, mono or multi-channel interleaved).
# ---------------------------------------------------------------------------

def write_wav24(path, samples, sample_rate):
    num_channels = 1
    bits_per_sample = 24
    bytes_per_sample = bits_per_sample // 8
    block_align = num_channels * bytes_per_sample
    byte_rate = sample_rate * block_align

    frames = bytearray()
    clipped = 0
    peak_code = 0
    limit = (1 << 23) - 1
    for value in samples:
        # Round-half-away-from-zero to a symmetric 24-bit range. The symmetric
        # range (rather than -2^23) means a full-scale negative sample cannot
        # wrap, and the clip counter below must stay at zero for every shipped
        # asset.
        code = int(math.floor(abs(value) * limit + 0.5))
        if code > limit:
            code = limit
            clipped += 1
        peak_code = max(peak_code, code)
        if value < 0.0:
            code = -code
        frames += struct.pack("<i", code)[:3]

    data_size = len(frames)
    riff_size = 4 + (8 + 16) + (8 + data_size) + (data_size % 2)

    with open(path, "wb") as handle:
        handle.write(b"RIFF")
        handle.write(struct.pack("<I", riff_size))
        handle.write(b"WAVE")
        handle.write(b"fmt ")
        handle.write(struct.pack("<IHHIIHH", 16, 1, num_channels, sample_rate,
                                 byte_rate, block_align, bits_per_sample))
        handle.write(b"data")
        handle.write(struct.pack("<I", data_size))
        handle.write(bytes(frames))
        if data_size % 2:
            handle.write(b"\x00")

    return clipped, peak_code / float(limit)


