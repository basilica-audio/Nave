def _dynamic_close_mic(proximity_db, proximity_hz=140.0, presence_db=2.5,
                       presence_hz=5200.0):
    """A generic cardioid dynamic microphone, close to the grille.

    Two effects, both first-principles rather than modelled on any particular
    microphone: the pressure-gradient proximity rise at close range (a
    low-shelf), and the mild presence lift a cardioid dynamic's diaphragm
    resonance contributes.
    """
    return [
        {"type": "lowshelf", "freq": proximity_hz, "q": 0.7, "gain_db": proximity_db},
        {"type": "peak", "freq": presence_hz, "q": 1.2, "gain_db": presence_db},
    ]


def _off_axis(corner_hz, shelf_db, extra_lp_hz):
    """Off-axis / cone-edge microphone placement.

    A cone radiates its high frequencies far more directionally than its lows,
    so moving the microphone off the dust cap towards the surround costs top
    end. Modelled as a high-shelf cut plus one extra low-pass pole.
    """
    return [
        {"type": "highshelf", "freq": corner_hz, "q": 0.7, "gain_db": shelf_db},
        {"type": "lowpass", "freq": extra_lp_hz, "q": 0.7},
    ]


